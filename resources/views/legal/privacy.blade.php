<p>This Privacy Policy explains what personal information PickSell collects through the PickSell website, the PickSell buyer app, the Pickrush rider app and the Pickrush partner portal (the "Platform"), why we collect it, who we share it with, how long we keep it, and the rights you have. PickSell is the personal information controller for the Platform. We process personal information in line with the <strong>Data Privacy Act of 2012 (Republic Act No. 10173)</strong>, its Implementing Rules and the issuances of the National Privacy Commission.</p>

<h2>1. What we collect</h2>
<h3>Everyone with an account</h3>
<ul>
    <li><strong>Identity and contact:</strong> name, sex, birthday and age, email address, mobile number, and your password (stored only as a one-way hash).</li>
    <li><strong>Address:</strong> province, city or municipality, barangay, street, house number and postal code.</li>
    <li><strong>Verification:</strong> the government ID you upload, and the one-time codes we email you.</li>
    <li><strong>Account activity:</strong> sign-ins, notifications, messages, reports, and the version of these terms you agreed to and when.</li>
</ul>
<h3>Buyers</h3>
<ul>
    <li>Orders, carts, wishlists, followed stores, recently viewed products, reviews and review photos, return requests and their photos.</li>
    <li>Saved delivery addresses, and the delivery pin you place on the map.</li>
</ul>
<h3>Sellers</h3>
<ul>
    <li>Business name, seller type, line of business, TIN, and business documents (business permit, DTI, SEC and BIR certificates, as your seller type requires).</li>
    <li>Your shop pin for pickups, store logo, banner and description, listings, prices, stock, vacation periods, delivery-partner choices, sales, commissions and payouts.</li>
</ul>
<h3>Riders and truck drivers</h3>
<ul>
    <li>Driver's license (number, expiry and photos), vehicle type and plate number, vehicle OR/CR and their expiry dates, and other documents the station asks for.</li>
    <li><strong>Location:</strong> the rider app records your location <em>only at the moments you tap an action that needs it</em>, such as "Arrived" at a pickup or a hub, or when you report a problem, so the system can confirm you are at the right place. It does not track you continuously.</li>
    <li>Proof-of-delivery photos, delivery attempts, cash collected and remitted, earnings, deductions, payslips and wallet withdrawals.</li>
</ul>
<h3>Logistics partners and their staff</h3>
<ul>
    <li>Company name and registration details, the owner's valid ID and business permit, staff names, roles, hub assignments and email addresses.</li>
</ul>
<h3>Collected automatically</h3>
<ul>
    <li>Basic technical data our servers log when you use the Platform (IP address, device and browser type, time of request) to keep it secure and fix problems.</li>
    <li>Product views and add-to-cart counts, used in totals for sellers' shop statistics.</li>
</ul>

<h2>2. Why we use it, and on what basis</h2>
<ul>
    <li><strong>To provide the service you signed up for</strong> (contract): creating and verifying your account, taking and delivering orders, collecting cash on delivery, returns and refunds, seller payouts and rider pay.</li>
    <li><strong>To keep the Platform safe and fair</strong> (legitimate interest): reviewing registrations and documents, preventing fraud and fake accounts, hiding contact details in buyer–seller chat and flagging off-platform deals, handling reports, disputes and strikes, and confirming rider arrivals by location.</li>
    <li><strong>To meet legal obligations</strong> (legal obligation): tax, accounting and audit records, and responding to lawful requests from authorities.</li>
    <li><strong>To tell you about your account and orders</strong>: order updates, approvals, payout and payslip notices, by in-app notification and email.</li>
    <li>Where the law requires your <strong>consent</strong>, we ask for it, and you can withdraw it at any time without affecting what was done before.</li>
</ul>
<p>We do not sell your personal information, and we do not use it for automated decisions that produce legal effects on you: penalties such as strikes and suspensions are decided by a person.</p>

<h2>3. Who can see it</h2>
<ul>
    <li><strong>The other side of your order.</strong> The seller sees the buyer's name, email, phone number, delivery address and pin, to prepare, send and support the order. The buyer sees the seller's store name and public store details.</li>
    <li><strong>The logistics partner, its hubs and the assigned rider</strong> see the names, addresses, phone numbers and pins needed to collect and deliver that parcel, and the amount to collect. Riders are bound to use them only for that delivery.</li>
    <li><strong>Other users</strong> see only what is public: store names, listings, and reviews (shown with the reviewer's first name, or first name and last initial in the app).</li>
    <li><strong>PickSell administrators</strong>, who need access to review registrations, listings, reports, disputes and payouts. Their actions on accounts are logged.</li>
    <li><strong>Service providers</strong> that help us run the Platform, under obligations to protect the data and use it only for us: our hosting, network (such as Cloudflare) and email delivery providers; content delivery networks that serve the map and font files (they see your IP address when your browser loads them); OpenStreetMap, whose map tiles and place search the map pickers use (the place you type or pick is sent to it to find it on the map); and the public Philippine Standard Geographic Code (PSGC) service, which supplies the province, city and barangay lists.</li>
    <li><strong>Authorities</strong>, when the law, a court order or a lawful request requires it, or when needed to protect someone's life, health or safety.</li>
</ul>

<h2>4. Cookies and storage on your device</h2>
<p>The website uses cookies needed to keep you signed in and protect forms from forgery. Your browser and apps also store a few settings on your device, such as dark mode, dismissed announcements and cached address lists. We do not use advertising or tracking cookies. Blocking the necessary cookies stops sign-in from working.</p>

<h2>5. How long we keep it</h2>
<ul>
    <li><strong>Your account</strong> is kept while it is open.</li>
    <li><strong>When you delete your account</strong> (possible once no order or return is in progress), we erase your name, email, phone, birthday, address, pins, uploaded IDs and business documents, store branding, cart, wishlist, saved addresses and follows, and you can no longer sign in.</li>
    <li><strong>Records of past orders, payments, returns, commissions and payouts</strong> are kept without your personal details, because the other party to the transaction, dispute handling, and tax and accounting laws require them. They are kept only as long as those purposes and laws require.</li>
    <li><strong>A disapproved registration's</strong> documents are kept only as long as needed to handle a resubmission or a complaint about the decision.</li>
</ul>

<h2>6. How we protect it</h2>
<ul>
    <li>Passwords are hashed and connections are encrypted. Uploaded IDs and documents are saved under random, unguessable file names and shown in the Platform only to the people who review them.</li>
    <li>Access is limited by role, and important account actions are recorded in an audit log.</li>
    <li>If a personal data breach puts you at real risk of serious harm, we will notify you and the National Privacy Commission as the law requires.</li>
</ul>
<p>No system is perfectly secure. Protect your account by keeping your password private and telling us right away if you think it was misused.</p>

<h2>7. Your rights</h2>
<p>Under the Data Privacy Act you have the right to:</p>
<ul>
    <li><strong>be informed</strong> about how your personal information is processed;</li>
    <li><strong>access</strong> it and get a copy;</li>
    <li><strong>correct</strong> it if it is wrong (most details you can change yourself on your account page);</li>
    <li><strong>object</strong> to processing, and to <strong>withdraw consent</strong> where processing relies on it;</li>
    <li>have it <strong>erased or blocked</strong> when it is no longer needed or was processed unlawfully (deleting your account does this for your profile);</li>
    <li><strong>data portability</strong>: get it in a commonly used electronic format;</li>
    <li>be indemnified for damages caused by inaccurate, unlawfully obtained or unauthorised use of your data; and</li>
    <li><strong>file a complaint</strong> with the National Privacy Commission (privacy.gov.ph).</li>
</ul>
<p>To use these rights, contact us through the <a href="{{ $contact }}">Contact page</a> and tell us which account it concerns. We may ask you to confirm your identity before acting, and we answer within the period the law requires. Some requests may be limited where we must keep records by law or for a pending dispute.</p>

<h2>8. Children</h2>
<p>The Platform is only for people aged 18 and over. We do not knowingly collect personal information from minors; if we learn that we have, we delete it.</p>

<h2>9. Changes to this policy</h2>
<p>We update this policy when the Platform or the law changes. The version date at the top shows the current one. For important changes we will give notice on the Platform before they apply.</p>

<h2>10. Contact</h2>
